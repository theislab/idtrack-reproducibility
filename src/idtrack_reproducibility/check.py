"""`idtrack-repro check`: the repository's tidiness, by checks (README, "Checks").

Fails (exit 1) on any of:

- text: a machine path, a mention of how the work was produced or of a private working record, a private review's
  finding or decision number, in any tracked file (`FORBIDDEN`);
- links: a relative Markdown link to a file that does not exist, or to a section (`#anchor`) the file does not have;
- families: a family package without its methods document (`docs/families/<family>.md`), its tests
  (`tests/test_family_<family>.py`) or, for a family with runs in `results.toml` that judges answers, its rows in the
  known-limitations table (`results/limitations/limitations.tsv`); a family without runs there yet is reported as
  skipped;
- results: a file under `results/` that is not in `results/index.tsv` or not generated by the pipeline (its
  provenance file names the command); an index row whose file is missing; a result whose recorded source (the scored
  run in the data root) has been scored again since (stale), or whose scored run has not its rows (the record,
  docs/records.md) in the data root, when the data root is present; a registered run whose scored folder is not of
  the entry's subject or reading of the input; a family that compares subjects with a folder not judged by today's
  judge; generated tables not made from every registered run of their family; a store of fetched responses whose
  manifest disagrees with the family's data manifest (results.py);
- manifests: a file of a data manifest (`manifests/**/*.tsv`) whose size or sha256 differs from the data root's
  (`--data`: every file; default: the sizes, and the sha256 of files under 50 MB), when the data root is present;
- style: a family, set, stratum or result file name outside the naming rules (docs/adding.md, "Names").

Without the data root (e.g. in CI) the data checks are reported as skipped, never as passed.
"""
import argparse
import csv
import glob
import hashlib
import os
import re
import subprocess
import sys

from . import config as CFG

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # the repository

# Text that must not appear in any tracked file. Each: (name, regex). The patterns are written so that this file
# does not match itself (character classes split the words).
FORBIDDEN = [
    ("machine path", r"/(?:home|lustre|ictstr0\d)/[A-Za-z0-9_.-]+|[A-Za-z]:\\\\Users\\\\|/Users/[a-z]"),
    ("cluster account or work folder", r"kemal[.]inecik|idtrack_upgrade_[w]ork|lustre_[w]orkspace|master_[i]dtrack"),
    ("production mention", r"\b[C]laude\b|\b[A]nthropic\b|\bAI [a]gents?\b|\b[s]ubagents?\b|\b[a]gents? (?:of|that|who|working)\b"),
    ("private working record", r"idtrack-[p]rivate|CONTINUE_[H]ERE|\b[p]rompts/|\b[Tt]he [l]ead\b|\b[Tt]he [o]wner\b|"
                               r"\bbrief_[v]ersion\b|\b[r]eview/[A-Za-z_0-9]+\.md|\bbench/(?:DESIGN|accuracy|families|scripts)\b|"
                               r"\b[s]ee the [r]eview\b"),
    ("agent or work-order name", r"\b[c]leanup_[a-z0-9_]+|\brepro_[f]ix\b|\b[b]riefs?\b"),
    ("private decision number", r"\b[Dd]ecisions? \d+|\b[Dd]ecision-\d+"),
    ("private review finding", r"\b(?:accuracy(?:_build|_track)?|graph(?:-new)?|structure|repo_packaging|web_setup|"
                               r"performance|tests|storage_net|organisms_externals)-(?:new-)?\d+\b|"
                               r"\b[A-H]\*?-\d{1,2}\b|\([f]inding\)"),
    ("private plan stage", r"\bS2[ab]\b|\bstage S\d\b|\bgate G\d\b"),
]
TEXT_SUFFIXES = (".py", ".md", ".toml", ".yml", ".yaml", ".tsv", ".json", ".txt", ".sh", ".cfg", ".ini")
NAME_RULES = {
    "family": r"^[a-z][a-z0-9]*$",
    "result file": r"^[a-z0-9][a-z0-9_.-]*$",
}


def tracked_files():
    r = subprocess.run(["git", "-C", ROOT, "ls-files", "-co", "--exclude-standard"], capture_output=True, text=True)
    return sorted(f for f in r.stdout.splitlines() if f and os.path.exists(os.path.join(ROOT, f)))


def check_text(files, problems):
    pats = [(n, re.compile(p)) for n, p in FORBIDDEN]
    import gzip
    for f in files:
        gz = f.endswith(".gz") and f[:-3].endswith(TEXT_SUFFIXES)  # the manifests of more than 5,000 rows
        if not gz and not f.endswith(TEXT_SUFFIXES) and os.path.basename(f) not in ("README", "LICENSE", ".gitignore"):
            continue
        try:
            text = (gzip.open if gz else open)(os.path.join(ROOT, f), "rt", encoding="utf-8").read()
        except UnicodeDecodeError:
            continue
        for i, line in enumerate(text.splitlines(), 1):
            for n, p in pats:
                m = p.search(line)
                if m:
                    problems.append(("text", f"{f}:{i}", f"{n}: {m.group(0)!r}"))


def anchors_of(path):
    """GitHub's anchors of a Markdown file's headings."""
    out, seen = set(), {}
    fence = False
    for line in open(path, encoding="utf-8"):
        if line.startswith("```"):
            fence = not fence
        m = None if fence else re.match(r"^#{1,6}\s+(.*?)\s*$", line)
        if m:
            a = re.sub(r"[^\w\- ]", "", m.group(1).strip().lower())
            a = a.replace(" ", "-")
            n = seen.get(a, 0)
            seen[a] = n + 1
            out.add(a if n == 0 else f"{a}-{n}")
    return out


def check_links(files, problems):
    link = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
    for f in files:
        if not f.endswith(".md"):
            continue
        base = os.path.dirname(os.path.join(ROOT, f))
        for i, line in enumerate(open(os.path.join(ROOT, f), encoding="utf-8"), 1):
            for target in link.findall(line):
                if re.match(r"^[a-z]+:", target):
                    continue  # a URL
                path, _, anchor = target.partition("#")
                full = os.path.normpath(os.path.join(base, path)) if path else os.path.join(ROOT, f)
                if not os.path.exists(full):
                    problems.append(("links", f"{f}:{i}", f"no such file: {target}"))
                    continue
                if anchor and full.endswith(".md") and anchor not in anchors_of(full):
                    problems.append(("links", f"{f}:{i}", f"no section #{anchor} in {os.path.relpath(full, ROOT)}"))


def families_in_package():
    d = os.path.join(ROOT, "src", "idtrack_reproducibility", "families")
    return sorted(x for x in os.listdir(d) if os.path.isdir(os.path.join(d, x)) and not x.startswith("_"))


def measures_answers(fam):
    """A family judges answers (and so has causes and limitation rows) unless its package says
    `MEASURES_ANSWERS = False` (performance: H measures time and memory, its limits are in its methods document)."""
    import importlib
    try:
        return getattr(importlib.import_module(f"idtrack_reproducibility.families.{fam}"), "MEASURES_ANSWERS", True)
    except Exception:  # noqa: BLE001  a family that does not import is reported by the tests
        return True


def families_with_results():
    """The families that have runs in the results registry (results.toml)."""
    import tomllib
    p = os.path.join(ROOT, "results.toml")
    if not os.path.exists(p):
        return set()
    with open(p, "rb") as fh:
        reg = tomllib.load(fh)
    return {e["family"] for e in reg.get("run", []) + reg.get("generated", [])}


def check_families(problems, skipped=None):
    lim = os.path.join(ROOT, "results", "limitations", "limitations.tsv")
    with_results = families_with_results()
    fams_lim = set()
    if os.path.exists(lim):
        with open(lim) as fh:
            fams_lim = {r["family"] for r in csv.DictReader(fh, delimiter="\t")}
    for fam in families_in_package():
        if not re.match(NAME_RULES["family"], fam):
            problems.append(("style", fam, "family name must match " + NAME_RULES["family"]))
        if not os.path.exists(os.path.join(ROOT, "docs", "families", f"{fam}.md")):
            problems.append(("families", fam, f"no methods document docs/families/{fam}.md"))
        if not os.path.exists(os.path.join(ROOT, "tests", f"test_family_{fam}.py")):
            problems.append(("families", fam, f"no tests tests/test_family_{fam}.py"))
        if fam not in with_results:  # built, not yet measured: nothing to derive results or limitations from
            if skipped is not None:
                skipped.append(f"family {fam}: no runs in results.toml yet (its results and limitation rows come with them)")
            continue
        classified = glob.glob(os.path.join(ROOT, "results", fam, "**", "*causes_summary.tsv"), recursive=True)
        if fam not in fams_lim and measures_answers(fam) and classified:
            problems.append(("families", fam, "no rows in results/limitations/limitations.tsv"))
        elif fam not in fams_lim and measures_answers(fam) and skipped is not None:
            skipped.append(f"family {fam}: none of its results is classified yet (its limitation rows come from its causes)")


def check_results(problems, skipped):
    from . import results as R
    R.check(ROOT, problems, skipped)
    pat = re.compile(NAME_RULES["result file"])
    for dp, _, fs in os.walk(os.path.join(ROOT, "results")):
        for f in fs:
            if not pat.match(f):
                problems.append(("style", os.path.relpath(os.path.join(dp, f), ROOT),
                                 "result file name must match " + NAME_RULES["result file"]))


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def check_manifests(problems, skipped, full):
    from . import manifests as M
    M.check(ROOT, problems, skipped, full)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="idtrack-repro check", description=__doc__.split("\n\n")[0])
    ap.add_argument("--data", action="store_true", help="also hash every file of the data manifests (slow)")
    ap.add_argument("--only", default=None, help="comma-separated: text,links,families,results,manifests")
    a = ap.parse_args(argv)
    only = set(a.only.split(",")) if a.only else {"text", "links", "families", "results", "manifests"}
    problems, skipped = [], []
    files = tracked_files()
    if "text" in only:
        check_text(files, problems)
    if "links" in only:
        check_links(files, problems)
    if "families" in only:
        check_families(problems, skipped)
    if "results" in only:
        check_results(problems, skipped)
    if "manifests" in only:
        check_manifests(problems, skipped, a.data)
    for kind, where, what in problems:
        print(f"{kind}\t{where}\t{what}")
    for s in skipped:
        print(f"skipped\t{s}")
    print(f"{len(problems)} problems, {len(skipped)} checks skipped", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
